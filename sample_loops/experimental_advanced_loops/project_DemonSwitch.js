
setCpm(136/4);

// ==========================================
// LEAD
// ==========================================

$: n("<0 4 0 9 7>*16"
    .add("<7 _ _ 6 5 _ _ 6>*2"))
  .scale("d:minor")
  .trans(slider(-18, -36, 0, 1))
  .sound("sawtooth")
  .lpf(slider(100, 40, 1000, 1))
  .lpenv(slider(13.5, 0, 25, .1))
  .lps(slider(.2, 0, 1, .01))
  .lpd(slider(.12, .01, 1, .01))
  .fm(slider(.8, 0, 4, .01))
  .fmwave("brown")
  .delay(slider(1.6, 0, 2, .01))
  .gain(slider(.31, 0, 1, .01))
  .pan(rand);

// ==========================================
// BASS
// ==========================================

$: n("<7 _ _ 6 5 _ <5 3> <6 4>>*4")
  .scale("a:minor")
  .trans(slider(-24, -36, -12, 1))
  .sound("supersaw")
  .lpf(slider(100, 40, 1000, 1))
  .lpenv(slider(16.3, 0, 25, .1))
  .lps(slider(.2, 0, 1, .01))
  .lpd(slider(.12, .01, 1, .01))
  .detune(rand)
  .gain(slider(.21, 0, .8, .01));

